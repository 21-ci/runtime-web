#!/usr/bin/env node
// Embeds web/dist into the deploy bundle as server/src/gen/ (gitignored).
//
//   node scripts/gen-assets.mjs [--dist ../web/dist] [--out src/gen] [--max-inline 700000]
//
// Output:
//   src/gen/assets.ts      manifest: path -> { type, etag, size, load? | blob? }
//   src/gen/a/<n>.ts       one module per inlined file (`export default` text or base64),
//                          loaded lazily so a task parses only the file it serves.
//   .gen-blobs.json        files over --max-inline (the bundle caps a file at 1 MB): the install
//                          script uploads them to std:blob in parts; spa.ts streams them back.
// Without a dist directory an empty manifest is written so typecheck and tests still run.
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const arg = (name, def) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : def;
};
const DIST = resolve(ROOT, arg("--dist", "../web/dist"));
const OUT = resolve(ROOT, arg("--out", "src/gen"));
const MAX_INLINE = Number(arg("--max-inline", "700000"));
export const PART_BYTES = 900_000;

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".map": "application/json",
  ".svg": "image/svg+xml",
  ".txt": "text/plain; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".wasm": "application/wasm",
};
const isText = (t) => t.startsWith("text/") || t.includes("json") || t.includes("svg");

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out.sort();
}

async function main() {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(join(OUT, "a"), { recursive: true });
  const entries = [];
  const blobs = [];
  const files = existsSync(DIST) ? await walk(DIST) : [];
  let n = 0;
  for (const f of files) {
    const path = "/" + relative(DIST, f).split(sep).join("/");
    const buf = await readFile(f);
    const type = TYPES[extname(f).toLowerCase()] ?? "application/octet-stream";
    const etag = `"${createHash("sha256").update(buf).digest("base64url").slice(0, 22)}"`;
    const meta = { type, etag, size: buf.length };
    if (buf.length > MAX_INLINE) {
      const parts = Math.ceil(buf.length / PART_BYTES);
      blobs.push({ path, file: f, ...meta, parts, partBytes: PART_BYTES });
      entries.push(`  ${JSON.stringify(path)}: ${JSON.stringify({ ...meta, blob: { parts } })},`);
      continue;
    }
    const text = isText(type);
    const body = text ? buf.toString("utf8") : buf.toString("base64");
    await writeFile(join(OUT, "a", `${n}.ts`), `export default ${JSON.stringify(body)};\n`);
    const m = JSON.stringify(meta).slice(0, -1);
    entries.push(`  ${JSON.stringify(path)}: ${m}, enc: "${text ? "text" : "b64"}", load: () => import("./a/${n}.ts") },`);
    n++;
  }
  const src = `// Generated by scripts/gen-assets.mjs from web/dist. Do not edit.
import type { AssetManifest } from "../spa.ts";

export const assets: AssetManifest = {
${entries.join("\n")}
};
`;
  await writeFile(join(OUT, "assets.ts"), src);
  await writeFile(join(ROOT, ".gen-blobs.json"), JSON.stringify(blobs, null, 2) + "\n");
  console.log(`gen-assets: ${files.length} files (${n} inline, ${blobs.length} blob) from ${existsSync(DIST) ? DIST : "<no dist>"}`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
